#!/usr/bin/env python3
"""S1 harness: a push changing a judge kernel file, or a module a whole gate row loads, needs the whole gate.

pre_push_gate.check_whole_gate counted only scripts/loop/ and the deploy list's named files as loop changes, so a
push of scripts/brother_run.py or of a required_fast row's own test file landed judged by its same-name tests alone
(decision D4). scripts/kernel_closure.txt is the closure the judge runs, and kernel_closure.py derives it from the
gate's run_check rows, so the test files every row runs and their imports are members: one list covers both halves.

The fixture is test_pre_push_whole_gate's: a throwaway repository, git's pre-push ref line on stdin, main() exactly as
the hook runs it, every other check stubbed out. The last case asks the landing's question the way land_batch does
(LOOP_ASK, run isolated against this tree's scripts as the frozen copy).

Written first, red on the base by assertion (1.1.8 stability release, owner ruling C2, 2026-10-24; spec
docs/plan/specs/1.1.9/S1.md). Done check: python3 -B scripts/test_kernel_whole_gate.py KernelChange
"""
import json
import os
import subprocess
import sys
import unittest
from unittest import mock

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "loop"))
import pre_push_gate as G  # noqa: E402
from test_pre_push_whole_gate import _Fixture, git  # noqa: E402

KERNEL = "# generated by python3 scripts/kernel_closure.py --write; never edit by hand\nscripts/brother_run.py\nscripts/test_row.py\n"


class KernelChange(_Fixture):
    def setUp(self):
        super().setUp()
        self.write("scripts/brother_run.py", "x = 1\n")
        self.write("scripts/test_row.py", "x = 1\n")
        self.base = self.commit("scripts/kernel_closure.txt", KERNEL)

    def test_a_kernel_file_is_a_loop_change(self):
        self.commit("scripts/brother_run.py", "x = 2\n")
        code, out = self.push()
        self.assertEqual(code, G.EXIT_BLOCKED, out)
        self.assertIn("scripts/brother_run.py", out)
        self.assertIn("sh scripts/required_fast.sh", out)

    def test_a_gate_row_module_is_a_loop_change(self):
        self.commit("scripts/test_row.py", "x = 2\n")
        code, out = self.push()
        self.assertEqual(code, G.EXIT_BLOCKED, out)
        self.assertIn("scripts/test_row.py", out)

    def test_a_file_outside_every_list_still_needs_nothing(self):
        self.commit("docs/note.md", "two\n")
        code, out = self.push()
        self.assertEqual(code, G.EXIT_OK, out)

    def test_a_record_for_the_exact_tree_clears_a_kernel_change(self):
        self.commit("scripts/brother_run.py", "x = 2\n")
        self.record_for_head()
        code, out = self.push()
        self.assertEqual(code, G.EXIT_OK, out)

    def test_unreadable_closure_fails_closed(self):
        tip = self.commit("docs/note.md", "two\n")
        real = G._git

        def no_list(args, cwd=G.ROOT, runner=None):
            if args == ["show", "%s:scripts/kernel_closure.txt" % tip]:
                return subprocess.CompletedProcess(args, 128, "", "fatal: unreadable")
            return real(args, cwd, runner)
        with mock.patch.object(G, "_git", no_list):
            code, out = self.push()
        self.assertEqual(code, G.EXIT_BLOCKED, out)
        self.assertIn("docs/note.md", out)

    def test_the_frozen_copy_agrees(self):
        import land_batch
        tip = self.commit("scripts/brother_run.py", "x = 2\n")
        line = "refs/heads/feature %s refs/heads/feature %s\n" % (tip, self.base)
        r = subprocess.run([sys.executable, "-I", "-B", "-c", land_batch.LOOP_ASK, HERE, self.repo],
                           input=line, capture_output=True, text=True, timeout=300)
        self.assertEqual(r.returncode, 0, r.stderr[-400:])
        said = json.loads(r.stdout.strip().splitlines()[-1])
        self.assertIn("BLOCK", [f[0] for f in said], said)
        self.assertIn("scripts/brother_run.py", " ".join(str(f[2]) for f in said))


if __name__ == "__main__":
    unittest.main()
