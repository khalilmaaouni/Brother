def shares(paths, budget, floor=20000, cap=110000, secondary=()):
    """Bytes per file, allocated BY NEED rather than evenly, and GUARANTEED to fit the budget.

    THE FILES THE SECTION NAMES COME FIRST, the neighbour suites take what is left (2026-09-24, run 2: D1.8's
    section named 8 files and the neighbour rule added 14 test suites beside them; 22 floors summed past the
    budget, everything was scaled down together, and the sub unit's OWN test file kept 265 of its 5716 bytes
    while loop_bridge and model_worker read NOT SHOWN under a 7514 byte share. A neighbour exists so an edit keeps
    it green; it never outranks the file the edit is made to). `secondary` names the neighbours; they are
    allocated by the same rule out of whatever the named files leave, and can honestly come back NOT SHOWN.

    WHY, measured 2026-09-21 over 40 consecutive grades: 37 failed and 3 passed, and the dominant verdict was
    RED-WITHOUT-CODE NO, meaning the tests passed even without the builder's own code. 36 of the 37 failing
    grades named unshown or sliced out source in their own UNKNOWNS, in their own words, for example
    "scripts/dream_authorize.py is not shown; its internals were not mutated or verified" and "sliced out blocks
    in dream_policy.py prevent mutating step, depth, node, and AST tag checks".

    The brief already carries "your tests must fail without your code" as hard rule 4. The builders were not
    ignoring it; they COULD NOT COMPLY, because an even split handed every named file budget // n. A section
    naming five files gave each about 39 kB, so the one large shared module the sub unit actually had to test was
    truncated, and a test written against code you cannot see is a test that passes either way.

    IT MUST ALSO FIT. The dispatcher refuses a prompt over 200000 bytes and the caller leaves only what is left
    after the head and the spec. Both this and the even split it replaces could exceed that: n files each floored
    at 20000 sum past the budget whenever n is large, and an oversized brief comes back WITHHELD, which is one of
    the blocked states this change exists to remove. So the floor is capped at the file's own size (a file
    smaller than the floor is complete, not starved) and the total is scaled to fit as a last resort."""
    secondary = set(secondary)
    if secondary and [p for p in paths if p not in secondary]:
        out = shares([p for p in paths if p not in secondary], budget, floor, cap)
        out.update(shares([p for p in paths if p in secondary], max(0, budget - sum(out.values())), floor, cap))
        return out
    need = {}
    for path in paths:
        try:
            need[path] = min(os.path.getsize(path), cap)
        except OSError:
            need[path] = floor          # unreadable size neither starves the file nor favours it
    if not paths:
        return {}
    total_need = sum(need.values()) or 1
    out = {}
    for path in paths:
        want = int(budget * need[path] / total_need)
        want = min(want, need[path])                  # never pad a file past its own size
        out[path] = max(want, min(floor, need[path]))  # the floor never exceeds the file itself
    # Hand any leftover to the files still short of what they need, largest need first: this is what gives the
    # big shared module its room once the small files have taken only what they are.
    spare = budget - sum(out.values())
    if spare > 0:
        for path in sorted(paths, key=lambda q: -need[q]):
            if spare <= 0:
                break
            add = min(spare, need[path] - out[path])
            if add > 0:
                out[path] += add
                spare -= add
    # A FLOOR RAISED A SMALL FILE PAST ITS PROPORTIONAL SHARE, so the sum can exceed the budget while every floor still
    # fits it (2026-09-29: a 33859 byte and a 6289 byte file under 40000; the scaling below cut the small file to 6285,
    # a stub). The excess comes out of the shares ABOVE their floor first, largest excess first; a floor is cut only
    # by the last resort below, when the floors themselves do not fit (and then everything scales together, which keeps
    # the largest need ahead of its siblings: trimming it to its floor first would tie them).
    over = sum(out.values()) - budget
    if sum(min(floor, need[q]) for q in paths) > budget:
        over = 0
    for path in sorted(paths, key=lambda q: -(out[q] - min(floor, need[q]))):
        if over <= 0:
            break
        give = min(over, out[path] - min(floor, need[path]))
        if give > 0:
            out[path] -= give
            over -= give
    # LAST RESORT, and it is a real case: many named files whose own floors already sum past the budget. Scale
    # everything down together rather than letting the brief overflow and come back WITHHELD.
    over = sum(out.values()) - budget
    if over > 0:
        scale = budget / max(1, sum(out.values()))
        for path in paths:
            out[path] = max(1, int(out[path] * scale))
        while sum(out.values()) > budget:
            worst = max(paths, key=lambda q: out[q])
            out[worst] -= 1
    return out


