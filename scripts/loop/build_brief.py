def lesson_block(unit: str, sub: str, runs_root: str, repo_root: str, now_utc: str,
                 budget: int = LESSON_BUDGET) -> str:
    """The eligible episodes of this sub unit, each traced to the receipt it was learned from (REQ-RL1-7).

    dream_episode is imported at load from the code root (model_router.code_root), so a code root without the
    plugin package, or a refused one, builds briefs as today with one NO-DATA line. Every run directory of this sub
    unit under runs_root (names starting '<sub>-') is read, newest by modification time first and never by the folder stamp;
    read_episodes then eligible with scope_of(repo_root, unit) and now_utc keep only the episodes this run may
    recall, and render_lessons bounds the block. No run directory of this sub unit at all returns '' (there is
    nothing to recall). Any failure (an argument that is not a non-empty string, a module that is missing, an
    unreadable runs_root, a raised step) returns one 'LESSONS NO-DATA: <reason>' line and never raises: a lesson
    that cannot be traced is withheld and the brief still builds (REQ-RL1-9)."""
    for label, value in (("unit", unit), ("sub", sub), ("runs_root", runs_root),
                         ("repo_root", repo_root), ("now_utc", now_utc)):
        if isinstance(value, bool) or not isinstance(value, str) or not value.strip():
            return "LESSONS NO-DATA: %s is not a non-empty string" % label
    if isinstance(budget, bool) or not isinstance(budget, int):
        return "LESSONS NO-DATA: budget is not an int number of bytes"
    try:
        module = _DE
        if module is None:
            if not os.path.isfile(_DREAM_EPISODE_PATH):
                return "LESSONS NO-DATA: dream_episode.py is not at %s" % _DREAM_EPISODE_PATH
            return "LESSONS NO-DATA: dream_episode.py at %s cannot be loaded: %s" % (_DREAM_EPISODE_PATH,
                                                                                     _DE_WHY[:200])
        names = os.listdir(runs_root)
        runs = []
        for name in names:
            if not name.startswith(sub + "-"):
                continue
            path = os.path.join(runs_root, name)
            if not os.path.isdir(path):
                continue
            try:
                runs.append((os.path.getmtime(path), name, path))
            except OSError:   # sbe: allow-silent an unstampable run is left out of the recall, never guessed at
                continue
        if not runs:
            return ""
        runs.sort(key=lambda run: (run[0], run[1]), reverse=True)
        scope = module.scope_of(repo_root, unit)
        kept = []
        for _stamp, _name, path in runs:
            rows = module.read_episodes(path)
            if rows is None:
                continue
            eligible_rows, _withheld = module.eligible(rows, scope, now_utc)
            kept.extend(eligible_rows)
        return module.render_lessons(kept, budget)
    except (OSError, ImportError, AttributeError, TypeError, ValueError, KeyError, RuntimeError) as exc:
        return "LESSONS NO-DATA: %s" % (str(exc)[:200] or type(exc).__name__)


