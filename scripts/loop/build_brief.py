def stale_claims(section_text, existing_paths):
    """Where the SPECIFICATION and the TREE disagree, stated as corrections the builder reads FIRST.

    THIS IS THE FIX FOR THE LARGEST MEASURED CAUSE OF A DEAD LANE. On 2026-09-21 a diagnostician round over 13
    stuck sub units returned 9 proven facts, and the same shape kept coming back: the spec asserts something is
    NEW and it already exists. Three of the nine verbatim: "scripts/loop_bridge.py already defines run_node, so
    D1.5's spec's claim that run_node is NEW is false"; "test_dream_world.py already exists with the TestSchema
    tests"; "dream_grade.py already contains the D9.d _classify implementation".

    The brief already listed which files exist, but the SPEC TEXT inside the same brief still said "create it".
    A builder handed two contradictory instructions spends its rounds trying to satisfy both, then exhausts, and
    the loop calls it a missing fact. It was never missing: it was present and contradicted.

    The deterministic scorer deliberately does NOT judge this case (its own comment: "NEW and present is NOT
    judged: an earlier sub unit of the same unit legitimately creates it"), and that exemption is right, because
    a sibling sub unit creating the file first is normal and healthy. The exemption is about whether the SPEC is
    WRONG; this function is about what the BUILDER IS TOLD. Both can be true: the spec stays valid, and the
    builder is told the file is already there.

    Fails toward saying nothing: anything unreadable is skipped, never guessed at, because a false correction
    would be worse than the silence it replaces. The occurrences of a path come from brief_check.labelled_paths,
    the one reader of every NEW spelling, inside the backticks (`NEW: p`, `p (NEW)`) or outside."""
    out = []
    for path in existing_paths:
        # the token's own label, or the words within about 120 characters of it, which is where a NEW marker sits
        for p, label, start, end in labelled_paths(section_text):
            if p != path:
                continue
            around = section_text[max(0, start - 120):end + 120]
            if label == "NEW" or re.search(r"\bNEW\b", around):
                out.append("%s is called NEW by the specification and ALREADY EXISTS on disk. Read it below, "
                           "extend it, and never recreate it." % path)
                break
    # symbols the section introduces as new that are already defined somewhere in the tree
    for sym in dict.fromkeys(re.findall(r"\b(?:new|add|create|introduce)s?\s+`([A-Za-z_][A-Za-z0-9_]*)\(`",
                                        section_text, re.I)):
        # NO PROCESS MODULE AT THE TOP OF THIS FILE (2026-09-24): the safety screen refused every build of this file
        # because it imported one at the top, and one import costs the whole build however narrow its use. The
        # search is the SAME search, done with the standard library: every .py file under the working directory,
        # the generated mirror under bundle/ and the interpreter's own caches left out, and the FIRST line that
        # defines the symbol. A file that cannot be read is skipped and a symbol that is not found is silence,
        # never a guess: the same fail-toward-saying-nothing direction as the rest of this function.
        first = []
        definition = re.compile(r"^[ \t]*(?:def|class)[ \t]+%s\b" % re.escape(sym))
        for base, dirnames, filenames in os.walk("."):
            dirnames[:] = sorted(d for d in dirnames
                                 if d not in ("bundle", ".git", "__pycache__", "node_modules",
                                              ".venv", "venv", ".mypy_cache", ".pytest_cache", ".tox"))
            for name in sorted(filenames):
                if not name.endswith(".py"):
                    continue
                rel = os.path.normpath(os.path.join(base, name))
                try:
                    with open(rel, encoding="utf-8", errors="replace") as fh:
                        for number, line in enumerate(fh, 1):
                            if definition.match(line):
                                first = ["%s:%d:%s" % (rel, number, line.rstrip("\n"))]
                                break
                except OSError:   # sbe: allow-silent an unreadable file is left out of the search, never guessed at
                    continue
                if first:
                    break
            if first:
                break
        if first:
            out.append("%s() is called new by the specification and is ALREADY DEFINED at %s. Call it, do not "
                       "redefine it." % (sym, first[0].split(":", 2)[0] + ":" + first[0].split(":", 2)[1]))
    return out


