#!/usr/bin/env python3
"""LM1.b: the grader refuses a bundle/ edit by name, with the remedy, before any sandbox work.

A loop build of scripts/loop/x.py is landed with its mirror regenerated by the landing; a build that writes bundle/
itself is refused here. Each case isolates one condition. The entry point case runs grade_build.py as a subprocess
under a throwaway HOME, so the machine slot lock files never touch the real home.
Run: python3 -B scripts/loop/test_grade_build_mirror.py
"""
import json
import os
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import grade_build as G  # noqa: E402

REMEDY = "bundle/ is generated: edit the source under scripts/loop, the landing regenerates the mirror"
CLEAN = {"path": "scripts/loop/x.py", "new_file_content": "x = 1\n"}


def edit(path):
    return {"path": path, "new_file_content": "x = 1\n"}


def unsafe(build):
    return G.unsafe(build, runners=frozenset())


class TheRule(unittest.TestCase):
    def test_an_edit_under_bundle_runtime_is_refused_with_the_remedy(self):
        why = unsafe({"edits": [edit("bundle/runtime/loop/x.py")]})
        self.assertEqual(why, REMEDY + " (bundle/runtime/loop/x.py)")

    def test_every_spelling_of_a_bundle_path_is_refused(self):
        for spelling in ("bundle", "Bundle/Runtime/x.py", "BUNDLE/x.py", "./bundle/x.py",
                         "scripts/../bundle/x.py", "bundle\\runtime\\x.py", "bundle//x.py", "./././bundle/x.py"):
            why = unsafe({"edits": [edit(spelling)]})
            self.assertIsInstance(why, str, spelling)
            self.assertTrue(why.startswith(REMEDY), (spelling, why))
            self.assertIn("(%s)" % spelling, why)

    def test_test_and_mutation_items_under_bundle_are_refused_too(self):
        self.assertTrue(unsafe({"edits": [CLEAN], "tests": [edit("bundle/t.py")]}).startswith(REMEDY))
        self.assertTrue(unsafe({"edits": [CLEAN], "mutations": [{"path": "bundle/m.py", "find": "a", "replace": "b"}]}
                               ).startswith(REMEDY))
        self.assertTrue(unsafe({"tests": [edit("bundle/t.py")]}).startswith(REMEDY))

    def test_the_first_offender_is_named_among_many(self):
        why = unsafe({"edits": [CLEAN, edit("bundle/a.py"), edit("bundle/b.py")]})
        self.assertEqual(why, REMEDY + " (bundle/a.py)")

    def test_a_loop_source_and_lookalike_folders_are_not_refused(self):
        for ok in ("scripts/loop/x.py", "bundles/x.py", "scripts/bundle/x.py", "docs/bundle/x.md", "bundle_x/y.py",
                   "mybundle/x.py"):
            self.assertIsNone(unsafe({"edits": [edit(ok)]}), ok)
        self.assertEqual(G.bundle_edit_reason({}), "")
        self.assertEqual(G.bundle_edit_reason({"edits": []}), "")

    def test_malformed_builds_never_crash_the_bundle_rule(self):
        for bad in ({"edits": "bundle/x.py"}, {"edits": [["bundle/x.py"]]}, {"edits": [{"path": None}]},
                    {"edits": [{"path": 5}]}, {"edits": [None, 3, "bundle/x.py"]}, {"tests": 7}, {"mutations": {"path": "bundle/x"}},
                    {"edits": [{"path": b"bundle/x"}]}, {"edits": [{}]}, None, [], "bundle/x.py", 5):
            try:
                self.assertEqual(G.bundle_edit_reason(bad), "", bad)
            except Exception as exc:  # noqa: BLE001
                self.fail("bundle_edit_reason(%r) raised %s: %s" % (bad, type(exc).__name__, exc))

    def test_a_resubmitted_bundle_path_is_refused_again_with_the_same_line(self):
        build = {"edits": [edit("bundle/runtime/loop/x.py")]}
        self.assertEqual(unsafe(build), unsafe(json.loads(json.dumps(build))))

    def test_the_refusal_holds_in_contained_mode_too(self):
        why = G.unsafe({"edits": [edit("bundle/x.py")]}, runners=frozenset(), contained=True)
        self.assertTrue(why.startswith(REMEDY))


class TheEntryPoint(unittest.TestCase):
    def test_the_grader_entry_point_prints_fail_safety_screen_with_the_remedy(self):
        with tempfile.TemporaryDirectory() as home, tempfile.TemporaryDirectory() as work:
            build = os.path.join(work, "build.json")
            with open(build, "w", encoding="utf-8") as fh:
                json.dump({"edits": [edit("bundle/runtime/loop/x.py")], "tests": [], "mutations": []}, fh)
            env = dict(os.environ, HOME=home)
            env.pop("BROTHER_GRADE_SANDBOXES", None)
            proc = subprocess.run([sys.executable, "-B", os.path.join(HERE, "grade_build.py"), build],
                                  cwd=os.path.dirname(os.path.dirname(HERE)), env=env, stdin=subprocess.DEVNULL,
                                  stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True, timeout=120)
            out = proc.stdout
            self.assertEqual(proc.returncode, 1, out)
            self.assertIn("FAIL safety screen: " + REMEDY, out)
            self.assertNotIn("APPLY", out)
            self.assertNotIn("RED-WITHOUT-CODE", out)


if __name__ == "__main__":
    unittest.main()
